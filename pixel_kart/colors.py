from enum import Enum

class Color(Enum):
    """
    Enumeration of colors used mostly for the GUI.

    Values are strings representing the color names.
    """
    SPECIAL = "white"
    GREY = "grey"
    WHITE = "white"
    BLACK = "black"
    ORANGE = "orange"
    RED = "red"
    BLUE = "blue"
    GREEN = "green"
    YELLOW = "yellow"
    PINK = "pink"
    PURPLE = "purple"
